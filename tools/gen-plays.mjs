// Writes the native play scripts (tests/native/*.play) from the rules: the
// content planner (src/content.js planContent: the moves that complete every
// discovery card) or a hand-written lesson plan is replayed in node and each
// command becomes the real UI's input — mouse clicks or finger touches on the
// tray buttons and on the named targets over the house's spots and pieces,
// or arrow keys + Enter through the keyboard cursor (its order and moves
// simulated exactly as native/main.ts builds them) — then Save scene ✦ and
// the results, checked against the simulated score rows.
//   node tools/gen-plays.mjs            (all scripts)
// dailyScript(date) is used by tests/native.mjs to play today's Daily.
