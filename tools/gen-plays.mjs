const ROOM_W = 4.2, ROOM_GAP = 0.28;

/** The keyboard cursor's targets (main.ts rebuildCursorTargets). */
function cursorTargets(content, st) {
  const cols = Math.max(...content.layout.rooms.map((r) => r.gx)) + 1;
  const houseW = cols * (ROOM_W + ROOM_GAP) - ROOM_GAP;
  const x0 = -houseW / 2 + ROOM_W / 2;
  const out = [];
  const rooms = st.rooms.slice().sort((a, b) => b.gy - a.gy || a.gx - b.gx);
  for (const room of rooms) {
    const cx = x0 + room.gx * (ROOM_W + ROOM_GAP);
    const n = room.slots.length;
    room.slots.forEach((item, slot) => {
      const t = n === 1 ? 0.5 : slot / (n - 1);
      out.push({ type: 'slot', room: room.id, slot, item, x: cx + (-ROOM_W / 2 + 0.85) + (ROOM_W - 1.7) * t, y: room.gy });
    });
  }
  const nT = content.tray.length;
  const trayW = Math.max(houseW * 0.7, nT * 1.15 + 1);
  st.tray.forEach((key, i) => {
    const t = Math.min((i + 0.5) / Math.max(nT, 1), 0.98);
    out.push({ type: 'tray', item: key, x: (-trayW / 2 + 0.7) + (trayW - 1.4) * t, y: -1 });
  });
  return out;
}
function moveIndex(T, i, dir) {
  if (i < 0) { const f = T.findIndex((t) => t.type === 'tray'); return f >= 0 ? f : 0; }
  const cur = T[i];
  if (dir === 'left' || dir === 'right') {
    const d = dir === 'left' ? -1 : 1;
    let j = i;
    for (let n = 0; n < T.length; n++) { j = (j + d + T.length) % T.length; if (T[j].y === cur.y) break; }
    return j;
  }
  const d = dir === 'up' ? 1 : -1;
  const rows = [...new Set(T.map((t) => t.y))].sort((a, b) => a - b);
  const nri = rows.indexOf(cur.y) + d;
  if (nri < 0 || nri >= rows.length) return i;
  let best = -1, bestDx = Infinity;
  T.forEach((t, k) => { if (t.y !== rows[nri]) return; const dx = Math.abs(t.x - cur.x); if (dx < bestDx) { bestDx = dx; best = k; } });
  return best >= 0 ? best : i;
}
const KEY = { left: 'ArrowLeft', right: 'ArrowRight', up: 'ArrowUp', down: 'ArrowDown' };
/** The arrow presses that bring the cursor from index i to a target matching `want` (breadth-first). */
function route(T, i, want) {
  const seen = new Map([[i, []]]);
  const q = [i];
  while (q.length) {
    const k = q.shift();
    if (k >= 0 && want(T[k])) return { keys: seen.get(k), index: k };
    for (const dir of ['left', 'right', 'up', 'down']) {
      const n = moveIndex(T, k, dir);
      if (!seen.has(n)) { seen.set(n, [...seen.get(k), dir]); q.push(n); }
    }
  }
  throw new Error('cursor cannot reach target');
}

/** A script writer for one layout and input style. */
class Script {
  constructor(header, viewport, input) {
    this.lines = [`# Generated by tools/gen-plays.mjs: ${header}`, `# viewport ${viewport}`];
    this.input = input; // 'click' | 'touch' | 'keys'
    const [w, h] = viewport.split('@')[0].split('x').map(Number);
    this.compact = !(w >= 1024 && !(w > h && h <= 500)); // screens.ts layoutNow: rails are drawers
    this.cursor = -1;
  }
  add(...l) { this.lines.push(...l); }
  tap(text) { this.add('frames 5', `${this.input === 'touch' ? 'touch' : 'click'} ${text}`); }
  text() { return this.lines.join('\n') + '\n'; }
  /** The countdown runs before the house takes input. */
  waitActive(label) { this.add(`until 600 ${label}`, 'frames 220'); }
  actions(fn) {
    if (this.compact) { this.tap('=Actions'); this.add('frames 10'); }
    fn();
    if (this.compact) { this.add('frames 10'); this.tap('=Actions'); this.add('frames 10'); }
  }
  keyTo(content, st, want) {
    const T = cursorTargets(content, st);
    const r = route(T, this.cursor, want);
    for (const d of r.keys) this.add(`key ${KEY[d]} 1`, 'frames 2');
    if (this.cursor < 0 && !r.keys.length) { this.add(`key ${KEY.right} 1`, 'frames 2'); }
    this.cursor = r.index;
    this.add('key Enter 1', 'frames 12');
  }
  /** After a command: the cursor keeps its slot (or tray piece), else resets (main.ts rebuildCursorTargets). */
  resync(content, before, st) {
    if (this.cursor < 0) return;
    const prev = cursorTargets(content, before)[this.cursor];
    const T = cursorTargets(content, st);
    this.cursor = T.findIndex((t) => t.type === prev.type && (t.type === 'tray' ? t.item === prev.item : t.room === prev.room && t.slot === prev.slot));
  }
}
const pieceTarget = (st, key) => {
  const p = R.itemSlot(st, key);
  return `=${itemName(key)} in the ${roomName(p.room)}, spot ${p.slot + 1}`;
};
const spotTarget = (st, room, slot) => `=${roomName(R.roomById(st, room))}, empty spot ${slot + 1}`;
const clone = (s) => JSON.parse(JSON.stringify(s));

/** One story played through the UI to its results. */
function playStory(sc, content, commands, label) {
  const st = R.createGame(content);
  sc.add(`# ${content.contentId} ${label}`);
  sc.waitActive('⏱');
  sc.cursor = -1;
  for (const cmd of commands) {
    const before = clone(st);
    if (sc.input === 'keys' && cmd.type !== 'remove') {
      if (cmd.type === 'place') {
        sc.keyTo(content, st, (t) => t.type === 'tray' && t.item === cmd.item);
        sc.keyTo(content, st, (t) => t.type === 'slot' && t.room === cmd.room && t.slot === cmd.slot);
      } else if (cmd.type === 'move') {
        sc.keyTo(content, st, (t) => t.type === 'slot' && t.item === cmd.item);
        sc.keyTo(content, st, (t) => t.type === 'slot' && t.room === cmd.room && t.slot === cmd.slot);
      } else if (cmd.type === 'interact') {
        sc.keyTo(content, st, (t) => t.type === 'slot' && t.item === cmd.a);
        sc.keyTo(content, st, (t) => t.type === 'slot' && t.item === cmd.b);
      }
    } else if (cmd.type === 'place') { sc.tap(`=${itemName(cmd.item)}`); sc.tap(spotTarget(st, cmd.room, cmd.slot)); }
    else if (cmd.type === 'move') { sc.tap(pieceTarget(st, cmd.item)); sc.tap(spotTarget(st, cmd.room, cmd.slot)); }
    else if (cmd.type === 'interact') { sc.tap(pieceTarget(st, cmd.a)); sc.tap(pieceTarget(st, cmd.b)); }
    else if (cmd.type === 'remove') {
      sc.tap(pieceTarget(st, cmd.item));
      sc.actions(() => sc.tap(`=↩ Return ${itemName(cmd.item)} to the tray`));
    }
    const { events } = R.applyCommand(st, cmd);
    if (events.some((e) => e.type === 'invalid')) throw new Error(`${content.contentId}: rejected ${JSON.stringify(cmd)}`);
    sc.resync(content, before, st);
    sc.add('frames 24');
  }
  const pending = st.cardDefs.some((c) => st.cards[c.id] === 0);
  sc.actions(() => sc.tap('=Save scene ✦'));
  if (pending && st.beats.length === 0) { sc.add('until 120 Save an empty story?', 'frames 10'); sc.tap('=Save scene'); }
  R.applyCommand(st, { type: 'finish', elapsedMs: 0 });
  const s = R.scoreState(st);
  sc.add('until 600 Invalid actions', 'frames 30', `expect ${s.moments} (${s.beats} beats)`, `expect ${s.discoveries} (${s.cardsDone}/${s.cardsTotal} cards)`);
  return s;
}

